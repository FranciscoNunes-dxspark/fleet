const PACKAGE = { dependencies: { express: '^4.17.1', 'string-width': '^1.0.2 || 2 || 3 || 4' }, devDependencies: { typescript: '^5.4.0', '@babel/code-frame': '^7.10.4' } };

test("Yarn 1's yarn.lock: every package once, direct ones from package.json, development's walked from them, git and aliases sorted out", () => {
  const list = parseYarnLock(YARN1, [PACKAGE]);
  const by = Object.fromEntries(list.map((p) => [`${p.name}@${p.version}`, p]));
  assert.deepEqual(Object.keys(by).sort(), ['@babel/code-frame@7.12.13', '@babel/highlight@7.13.10', 'debug@2.6.9', 'express@4.17.1', 'ms@2.0.0', 'string-width@4.2.3', 'typescript@5.4.5']);
  assert.deepEqual([by['express@4.17.1'].direct, by['express@4.17.1'].dev], [true, false]);
  assert.deepEqual([by['debug@2.6.9'].direct, by['debug@2.6.9'].dev], [false, false]);
  assert.deepEqual([by['typescript@5.4.5'].direct, by['typescript@5.4.5'].dev], [true, true]);
  assert.equal(by['@babel/highlight@7.13.10'].dev, true, 'only a development package brings it in');
  assert.equal(by['string-width@4.2.3'].direct, true);
  assert.equal(by['express@4.17.1'].line, YARN1.split('\n').indexOf('express@^4.17.1:') + 1);
  // With no package.json, nothing can be told: none direct, none development's.
  assert.ok(parseYarnLock(YARN1).every((p) => !p.direct && !p.dev));
});

