  const list = parsePnpmLock(PNPM9);
  const by = Object.fromEntries(list.map((p) => [`${p.name}@${p.version}`, p]));
  assert.deepEqual(Object.keys(by).sort(), ['@babel/core@7.22.0', 'debug@2.6.9', 'express@4.17.1', 'ms@2.1.3', 'react-dom@18.2.0', 'react@18.2.0', 'string-width@4.2.3']);
