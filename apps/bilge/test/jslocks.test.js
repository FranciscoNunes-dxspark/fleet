test("Berry's yarn.lock: npm's packages by their resolution, the workspaces' dependencies direct, a patch and the workspaces left out", () => {
  const list = parseYarnLock(BERRY, [{ dependencies: { express: '^4.17.1' }, devDependencies: { 'react-dom': '^18.2.0' } }]);
  const by = Object.fromEntries(list.map((p) => [`${p.name}@${p.version}`, p]));
  assert.deepEqual(Object.keys(by).sort(), ['debug@2.6.9', 'express@4.17.1', 'react-dom@18.2.0']);
  assert.deepEqual([by['express@4.17.1'].direct, by['debug@2.6.9'].direct, by['react-dom@18.2.0'].direct], [true, false, true]);
  assert.equal(by['react-dom@18.2.0'].dev, true);
  assert.equal(by['debug@2.6.9'].dev, false);
  assert.deepEqual(by['react-dom@18.2.0'].peers, { react: '^18.2.0' });
});

